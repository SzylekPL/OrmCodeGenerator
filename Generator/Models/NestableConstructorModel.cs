using OrmGenerator.Models.Field;
using OrmGenerator.Models.Property;
using Shared;
using System;
using System.Collections.Immutable;
using System.Text;

namespace OrmGenerator.Models;

internal sealed class NestableConstructorModel(string name, string @namespace, ImmutableArray<IField> parameters, bool generateToString) : ModelDeclaration(name, @namespace, generateToString), IEquatable<NestableConstructorModel>
{
	private readonly ImmutableArray<IField> _parameters = parameters;

	public override bool Equals(ModelDeclaration other) => other is NestableConstructorModel d && Equals(d);
	public bool Equals(NestableConstructorModel other)
	{
		if (_name != other._name || _namespace != other._namespace || _parameters.Length != other._parameters.Length)
			return false;

		for (int i = 0; i < _parameters.Length; i++)
			if (!_parameters[i].Equals(other._parameters[i]))
				return false;
		return true;
	}

	public override string SourceCode
	{
		get
		{
			StringBuilder builder = new();

			builder.AppendLine(
			$$"""
			/// <auto-generated/>

			using System.Data.Common;
			using OrmGenerator;

			namespace {{_namespace}};
			partial record {{_name}} : IOrmModel<{{_name}}>
			{
				public static {{_name}} GetSingleModel(DbDataReader reader, ref int index) => new(
			""");

			foreach (IField prop in _parameters)
			{
				if (prop is CustomField c)
					builder.AppendLine($"		{c.Type}.GetSingleModel(reader, ref index),");
				else
				{
					NativeField s = (NativeField)prop;
					builder.AppendLine($@"		reader.Get{s.Type.CsString}(index++),");
				}
			}

			builder.Remove(builder.Length - 3, 3)
				.AppendLine(@"	);");

			if (_generateToString)
			{
				builder.AppendLine($$""""
						public override string ToString() =>
							$"""
					"""");
				foreach (IField prop in _parameters)
					builder.AppendLine($@"		{prop.Name}: {{{prop.Name}}}");
				builder.AppendLine("		\"\"\";");
			}
			builder.AppendLine("}");

			return builder.ToString();
		}
	}
}

