using Shared;
using System;
using System.Collections.Immutable;
using System.Text;

namespace OrmGenerator.Models;

internal class PropertyModel(string name, string @namespace, bool generateToString, bool isRecord, ImmutableArray<Field> fields)
	: ModelDeclaration(name, @namespace, generateToString, isRecord, fields), IEquatable<PropertyModel>
{
	public override bool Equals(ModelDeclaration other) => other is PropertyModel d && Equals(d);
	public bool Equals(PropertyModel other)
	{
		if (_name != other._name || _namespace != other._namespace || _fields.Length != other._fields.Length)
			return false;

		for (int i = 0; i < _fields.Length; i++)
			if (!_fields[i].Equals(other._fields[i]))
				return false;
		return true;
	}
	public override string SourceCode
	{
		get
		{
			StringBuilder builder = new();

			builder.AppendLine(
			$$"""
			/// <auto-generated/>

			using System.Data.Common;
			using OrmGenerator;

			namespace {{_namespace}};
			partial {{(_isRecord ? "record" : "class")}} {{_name}} : IOrmModel<{{_name}}>
			{
				public static {{_name}} GetSingleModel(DbDataReader reader, ref int index) => new()
				{
			""");

			foreach (Field prop in _fields)
			{
				if (Constants.DbDataTypes.Contains(prop.Type))
				{
					builder.AppendLine($"		{prop.Name} = reader.Get{prop.Type}(index++),");
					continue;
				}
				builder.AppendLine($"		{prop.Name} = {prop.Type}.GetSingleModel(reader, ref index),");
			}


			builder.AppendLine(@"	};");
			if (_generateToString)
			{
				builder.AppendLine($$""""
						public override string ToString() =>
							$"""
					"""");
				foreach (Field prop in _fields)
					builder.AppendLine($@"		{prop.Name}: {{{prop.Name}}}");
				builder.AppendLine("		\"\"\";");
			}
			builder.AppendLine("}");

			return builder.ToString();
		}
	}
}
